package com.ogfa.nativeviews.animation.aftereffect;

public class AnimationWindow {

    public final float width;
    public final float height;
    public final float left;
    public final float top;

    public AnimationWindow(float width, float height, float left, float top) {
        this.width = width;
        this.height = height;
        this.left = left;
        this.top = top;
    }
}
